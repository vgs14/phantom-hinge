#!/bin/sh
# Packages overlay-src/ into config.apkovl.tar.gz and drops it in
# http/alpine/, where boot.ipxe expects to find it.
#
# Intended to be run from build.sh but safe to re-run any time you edit files
# under overlay-src/ (e.g. to change the kiosk URL, add packages to etc/apk/world,
# add users, etc). No internet required.

set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/overlay-src"
OUT="$ROOT/http/alpine/config.apkovl.tar.gz"

mkdir -p "$ROOT/http/alpine"

# Work on a throwaway copy of overlay-src, so file modes and runlevel
# symlinks come out right regardless of how the repo was checked out (git
# doesn't reliably preserve either - e.g. with core.symlinks=false, or a
# clone made under a restrictive umask) and without touching the source
# tree itself.
STAGE="$(mktemp -d)"
trap 'rm -rf "${STAGE}"' EXIT
cp -a "${SRC}/." "${STAGE}/"

# Splash image generated by 03-splash.sh, if there is one. Without it,
# splashd quietly does nothing at boot.
if [ -f "${ROOT}/build/splash.ppm" ]; then
    echo "==> Including splash image"
    mkdir -p "${STAGE}/etc/splash"
    cp "${ROOT}/build/splash.ppm" "${STAGE}/etc/splash/splash.ppm"
fi

# Sway's desktop background (included from etc/sway/kiosk-config). With a
# splash, it's the splash image, centred and unscaled on black - exactly
# how fbsplash draws it - so it carries on showing while Sway and Chromium
# start, instead of a black screen. Generated rather than kept in
# overlay-src because Sway reports a config error (on screen) if a
# background image is missing.
if [ -f "${ROOT}/build/splash.png" ]; then
    cp "${ROOT}/build/splash.png" "${STAGE}/etc/splash/splash.png"
    echo "output * bg /etc/splash/splash.png center #000000" > "${STAGE}/etc/sway/background.conf"
else
    echo "output * bg #000000 solid_color" > "${STAGE}/etc/sway/background.conf"
fi

# Dev SSH key staged by 02-devmode.sh, if there is one. Only used when
# devmode= is set at boot (see etc/init.d/devmode).
if [ -f "${ROOT}/build/ssh-dev/authorized_keys" ]; then
    echo "==> Including dev SSH authorized_keys"
    mkdir -p "${STAGE}/etc/ssh-dev"
    cp "${ROOT}/build/ssh-dev/authorized_keys" "${STAGE}/etc/ssh-dev/authorized_keys"
fi

# The kiosk URL (start-chromium.sh) and the Chromium policy allowlist
# (kiosk.json) have to agree, or Chromium shows "blocked by your
# administrator" instead of the app. Catch that here rather than at boot.
python3 - "${STAGE}/etc/sway/start-chromium.sh" \
    "${STAGE}/etc/chromium/policies/managed/kiosk.json" <<'EOF'
import json, re, sys
from urllib.parse import urlsplit

script, policy = sys.argv[1], sys.argv[2]
m = re.search(r'^URL="([^"]+)"', open(script).read(), re.M)
if not m:
    sys.exit(f"ERROR: couldn't find URL=\"...\" in {script}")
url = urlsplit(m.group(1))
allow = json.load(open(policy)).get("URLAllowlist", [])

def covers(entry):
    if entry == "*":
        return True
    e = urlsplit(entry if "://" in entry else "//" + entry)
    if e.scheme and e.scheme != url.scheme:
        return False
    if e.port and e.port != url.port:
        return False
    # Chromium URL filter format: "example.com" also matches subdomains,
    # a leading dot (".example.com") means that exact host only.
    host = e.hostname or ""
    if entry.lstrip("/").startswith("."):
        return url.hostname == host.lstrip(".")
    return url.hostname == host or url.hostname.endswith("." + host)

if not any(covers(a) for a in allow):
    sys.exit(f"ERROR: kiosk URL {m.group(1)} isn't covered by URLAllowlist {allow} "
             f"in kiosk.json - Chromium would block it. Add its origin there.")
EOF

# Permission fixes. Everything readable by everyone (the kiosk and
# appbackend users need to read their configs), then exec bits on the
# things that actually get run.
chmod -R u=rwX,go=rX "${STAGE}"
chmod 755 "${STAGE}"/etc/init.d/* "${STAGE}"/etc/local.d/*.start \
    "${STAGE}/etc/sway/start-chromium.sh"

# Runlevel entries. Each file under overlay-src/etc/runlevels/<level>/ just
# names a service to enable - its content doesn't matter. OpenRC expects a
# symlink to /etc/init.d/<name>, so replace each one with exactly that.
# Services like dbus/seatd/udev come from apk packages rather than this
# overlay, so the link target won't exist here - that's expected.
echo "==> Creating runlevel symlinks"
for entry in "${STAGE}"/etc/runlevels/*/*; do
    [ -e "${entry}" ] || [ -L "${entry}" ] || continue
    name="$(basename "${entry}")"
    rm -f "${entry}"
    ln -s "/etc/init.d/${name}" "${entry}"
    echo "    $(basename "$(dirname "${entry}")")/${name} -> /etc/init.d/${name}"
done

echo "==> Building $OUT from $SRC"
# tar with --numeric-owner keeps this reproducible regardless of the
# building machine's local user/group name mappings; Alpine's apkovl
# loader doesn't care about ownership beyond root anyway.
#
# Everything at the top level of overlay-src goes in (etc, opt, and
# anything you add such as usr or root), not a hardcoded list - otherwise
# a new top-level directory would silently never reach the kiosk. Listed
# by name rather than as "." so entries come out as etc/... not ./etc/...,
# which is the layout Alpine's own lbu-made apkovls use.
( cd "$STAGE" && set -- * && tar czf "$OUT" --numeric-owner --owner=0 --group=0 "$@" )

echo "==> Done: $OUT"
tar tzf "$OUT" | head -30
echo "    ($(tar tzf "$OUT" | wc -l) files total)"
